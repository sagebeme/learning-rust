//! `cargo xtask site-data`: writes `site/assets/course.js`, the project and guide list the course
//! site reads. The site is plain static files, so this list is committed. Run it again whenever a
//! project, task or guide is added or renamed; CI runs it with `--check`.

use std::fs;
use std::path::Path;

use serde_json::{Value, json};

use crate::course;

const REPO: &str = "https://github.com/sagebeme/learning-rust";

/// One line per week, from the README's "The 8 weeks" table.
const WEEKS: [&str; 8] = [
    "Tooling, values, functions, and the Tauri spike",
    "Ownership, and modelling with types",
    "Errors and files, collections, smart pointers",
    "Traits and dates, then the rules engine",
    "The engine inside the Tauri app",
    "Postgres with sqlx",
    "The async backend and the daily alerts",
    "Architecture, reviews and the client demo",
];

pub fn run(check: bool) -> Result<(), String> {
    let root = course::workspace_root();
    let projects: Vec<Value> = course::projects(&root)?
        .iter()
        .map(|project| {
            let tasks: Vec<Value> = project
                .tasks
                .iter()
                .map(|task| {
                    json!({
                        "id": task.id,
                        "number": task.number,
                        "file": task.file,
                        "title": task.title,
                        "advanced": task.advanced,
                    })
                })
                .collect();
            json!({
                "dir": project.dir,
                "number": project.number,
                "package": project.package,
                "title": project.title,
                "week": project.week,
                "summary": project.summary,
                "review": project.has_review,
                "tasks": tasks,
            })
        })
        .collect();

    let weeks: Vec<Value> = WEEKS
        .iter()
        .enumerate()
        .map(|(index, theme)| json!({ "n": index + 1, "theme": theme }))
        .collect();

    let data = json!({
        "repo": REPO,
        "weeks": weeks,
        "projects": projects,
        "guides": guides(&root)?,
    });
    let text = serde_json::to_string_pretty(&data).map_err(|error| error.to_string())?;
    let file = format!(
        "// Generated by `cargo xtask site-data` from the project folders. Don't edit by hand.\n\
         window.RS_COURSE = {text};\n"
    );

    let out = root.join("site").join("assets").join("course.js");
    if check {
        let current = fs::read_to_string(&out).unwrap_or_default();
        if current.replace("\r\n", "\n") != file {
            return Err(
                "site/assets/course.js is out of date. Run `cargo xtask site-data` and commit it."
                    .to_string(),
            );
        }
        println!("site/assets/course.js is up to date.");
    } else {
        fs::write(&out, file).map_err(|error| format!("can't write {}: {error}", out.display()))?;
        println!("Wrote site/assets/course.js: {} projects.", projects.len());
    }
    Ok(())
}

/// Every Markdown page under `docs/`, with its heading as the title, in folder order.
fn guides(root: &Path) -> Result<Vec<Value>, String> {
    let mut found = Vec::new();
    collect_markdown(root, Path::new("docs"), &mut found)?;
    found.sort();
    Ok(found
        .into_iter()
        .map(|(path, title)| json!({ "path": path, "title": title }))
        .collect())
}

fn collect_markdown(
    root: &Path,
    relative: &Path,
    found: &mut Vec<(String, String)>,
) -> Result<(), String> {
    let dir = root.join(relative);
    let entries =
        fs::read_dir(&dir).map_err(|error| format!("can't list {}: {error}", dir.display()))?;
    for entry in entries.filter_map(|entry| entry.ok()) {
        let name = entry.file_name().to_string_lossy().into_owned();
        let path = relative.join(&name);
        if entry.path().is_dir() {
            collect_markdown(root, &path, found)?;
        } else if name.ends_with(".md") {
            let text = fs::read_to_string(entry.path()).map_err(|error| error.to_string())?;
            let title = text
                .lines()
                .find_map(|line| line.strip_prefix("# "))
                .unwrap_or(&name)
                .trim()
                .to_string();
            found.push((path.to_string_lossy().replace('\\', "/"), title));
        }
    }
    Ok(())
}
